/**
 * A real agent session against the MCP server, for docs/agent-session.md:
 * `node apps/local/src/agent-session.ts > docs/agent-session.md`.
 * Starts the server on a fresh synthetic workspace, speaks raw JSON-RPC over stdio (what any MCP
 * client does), and writes each call and a trimmed result as Markdown. Synthetic data only.
 */
import { spawn } from "node:child_process";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Workspace } from "@chatterpilot/storage";

const ROOT = new URL("../../../", import.meta.url).pathname;

type Json = Record<string, unknown>;

export async function recordSession(): Promise<string> {
  const dir = mkdtempSync(join(tmpdir(), "chatterpilot-session-"));
  Workspace.create(join(dir, "ws"), {
    name: "Agent session demo",
    timezone: "Asia/Kolkata",
  }).close();
  const child = spawn(
    process.execPath,
    [
      "apps/local/src/cli.ts",
      "mcp",
      "--workspace",
      join(dir, "ws"),
      "--files",
      join(ROOT, "fixtures/synthetic"),
      "--agent",
      "demo-agent",
    ],
    { cwd: ROOT },
  );
  const pending = new Map<number, (msg: Json) => void>();
  let buffer = "";
  child.stdout.on("data", (chunk: Buffer) => {
    buffer += chunk.toString("utf8");
    for (let nl = buffer.indexOf("\n"); nl >= 0; nl = buffer.indexOf("\n")) {
      const line = buffer.slice(0, nl).trim();
      buffer = buffer.slice(nl + 1);
      if (!line) continue;
      const msg = JSON.parse(line) as Json;
      if (typeof msg.id === "number") pending.get(msg.id)?.(msg);
    }
  });
  let nextId = 1;
  const rpc = (method: string, params: unknown = {}) => {
    const id = nextId++;
    child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", id, method, params })}\n`);
    return new Promise<Json>((resolve) => pending.set(id, resolve));
  };
  const out: string[] = [];
  const show = (value: unknown, max = 1400) => {
    const text = JSON.stringify(value, null, 2);
    return text.length > max ? `${text.slice(0, max)}\n… (trimmed)` : text;
  };
  const call = async (title: string, name: string, args: Json, pick: (r: Json) => unknown) => {
    const res = (await rpc("tools/call", { name, arguments: args })) as {
      result?: { isError?: boolean; structuredContent?: Json; content?: { text: string }[] };
      error?: { message: string };
    };
    out.push(`### ${title}\n`);
    out.push("```json", show({ tool: name, arguments: args }), "```\n");
    const r = res.result;
    const body = res.error
      ? { error: res.error.message }
      : r?.isError
        ? { isError: true, text: r.content?.[0]?.text }
        : pick(r?.structuredContent ?? {});
    out.push("Result:\n", "```json", show(body), "```\n");
    return r?.structuredContent ?? {};
  };

  try {
    await rpc("initialize", {
      protocolVersion: "2025-11-25",
      capabilities: {},
      clientInfo: { name: "agent-session", version: "0" },
    });
    child.stdin.write(
      `${JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" })}\n`,
    );
    const tools = (await rpc("tools/list")) as { result: { tools: { name: string }[] } };
    out.push(
      "# A recorded agent session",
      "",
      "Generated by `node apps/local/src/agent-session.ts` against a fresh workspace with the",
      "synthetic fixtures. This is the real server output (trimmed), showing what a coding agent can",
      "and cannot do through MCP. Regenerate it after changing the tools.",
      "",
      `The server offers ${tools.result.tools.length} tools: ${tools.result.tools.map((t) => `\`${t.name}\``).join(", ")}.`,
      "",
    );
    await call("1. Load the price list", "load_catalogue", { dir: "catalogue" }, (r) => ({
      usable: r.usable,
      products: r.products,
      customers: r.customers,
    }));
    await call(
      "2. Import a Hinglish chat export",
      "import_export",
      { path: "chats/android-hinglish-orders.txt" },
      (r) => ({
        status: r.status,
        messages: (r.summary as Json | undefined)?.messages ?? r.messages,
      }),
    );
    const suggested = (await call(
      "3. Ask which messages look like orders",
      "list_suggestions",
      {},
      (r) => (r.suggestions as Json[]).map((s) => ({ messageId: s.messageId, text: s.text })),
    )) as { suggestions: { messageId: string }[] };
    const first = suggested.suggestions?.[0]?.messageId ?? "";
    const created = (await call(
      "4. Create a draft from the first one",
      "create_draft",
      { messageIds: [first] },
      (r) => {
        const draft = r.draft as { lines: Json[]; issues: Json[] };
        return {
          record: r.record,
          lines: draft.lines.map((l) => ({
            source: l.sourceText,
            product: (l.product as Json).value,
            quantity: (l.quantity as Json).value,
            evidence: ((l.quantity as Json).evidence as Json[])[0],
          })),
          issues: draft.issues,
        };
      },
    )) as { record?: { id: string } };
    await call(
      "5. Propose a correction (a person still decides)",
      "revise_draft",
      {
        draftId: created.record?.id ?? "",
        reason: "Customer confirmed 25 bags on the phone",
        change: { action: "set_line", line: 0, field: "quantity", value: "25" },
      },
      (r) => ({
        status: (r.record as Json).status,
        quantityEvidence: ((r.draft as { lines: { quantity: { evidence: Json[] } }[] }).lines[0]
          ?.quantity.evidence ?? [])[0],
      }),
    );
    await call(
      "6. Try to export to Tally (nothing accepted yet)",
      "export_orders",
      { format: "tally-xml" },
      (r) => r,
    );
    await call(
      "7. Try to accept the order",
      "accept_draft",
      { draftId: created.record?.id ?? "" },
      (r) => r,
    );
    await call(
      "8. What is still open in the chats?",
      "followups",
      {},
      (r) => (r as { summary: unknown }).summary,
    );
    out.push(
      "## What this shows",
      "",
      "- Every value the agent sees cites the chat line or catalogue row it came from.",
      "- The agent's edit is recorded as `agent:demo-agent` with its reason; the draft stays open.",
      "- There is no tool to accept an order, so an agent (or a message telling it to) cannot.",
      "- Exports refuse until a person has accepted something in the review app.",
      "",
    );
    return out.join("\n");
  } finally {
    child.kill();
    rmSync(dir, { recursive: true, force: true });
  }
}

if (import.meta.url === `file://${process.argv[1]}`) process.stdout.write(await recordSession());
