/**
 * Machine-readable references for coding agents, generated from the code so they cannot drift:
 *   node apps/local/src/agent-reference.ts   → docs/agents/tools.json and docs/agents/errors.md
 * tools.json is the MCP server's own tools/list answer. errors.md lists every error code the CLI
 * (--json) and MCP tools can return, with its exit code. A test regenerates both and compares.
 */
import { spawn } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Workspace } from "@chatterpilot/storage";

const ROOT = new URL("../../../", import.meta.url).pathname;
const SRC = join(ROOT, "apps/local/src");

interface Tool {
  name: string;
  title?: string;
  description?: string;
  inputSchema?: unknown;
  annotations?: Record<string, unknown>;
}

/** Asks a fresh MCP server (synthetic workspace) for its tool list over raw JSON-RPC. */
export async function listTools(): Promise<Tool[]> {
  const dir = mkdtempSync(join(tmpdir(), "chatterpilot-ref-"));
  Workspace.create(join(dir, "ws"), { name: "Reference", timezone: "Asia/Kolkata" }).close();
  const child = spawn(
    process.execPath,
    [
      "apps/local/src/cli.ts",
      "mcp",
      "--workspace",
      join(dir, "ws"),
      "--files",
      join(ROOT, "fixtures/synthetic"),
      "--agent",
      "reference",
    ],
    { cwd: ROOT },
  );
  try {
    const replies = new Map<number, (msg: Record<string, unknown>) => void>();
    let buffer = "";
    child.stdout.on("data", (chunk: Buffer) => {
      buffer += chunk.toString("utf8");
      for (let nl = buffer.indexOf("\n"); nl >= 0; nl = buffer.indexOf("\n")) {
        const line = buffer.slice(0, nl).trim();
        buffer = buffer.slice(nl + 1);
        if (!line) continue;
        const msg = JSON.parse(line) as Record<string, unknown>;
        if (typeof msg.id === "number") replies.get(msg.id)?.(msg);
      }
    });
    let id = 0;
    const rpc = (method: string, params: unknown = {}) => {
      const n = ++id;
      child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", id: n, method, params })}\n`);
      return new Promise<Record<string, unknown>>((resolve) => replies.set(n, resolve));
    };
    await rpc("initialize", {
      protocolVersion: "2025-06-18",
      capabilities: {},
      clientInfo: { name: "agent-reference", version: "1" },
    });
    child.stdin.write(
      `${JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" })}\n`,
    );
    const list = (await rpc("tools/list")) as { result: { tools: Tool[] } };
    return list.result.tools;
  } finally {
    child.kill();
    rmSync(dir, { recursive: true, force: true });
  }
}

export function toolsJson(tools: readonly Tool[]): string {
  const sorted = [...tools].sort((a, b) => a.name.localeCompare(b.name));
  return `${JSON.stringify(
    {
      $comment:
        "Generated by node apps/local/src/agent-reference.ts from the MCP server's tools/list. Do not edit by hand. There is deliberately no tool that accepts, rejects or submits an order.",
      server: "chatterpilot",
      start:
        "node apps/local/src/cli.ts mcp --workspace <dir> --files <allowed folder> --agent <name>",
      tools: sorted.map((t) => ({
        name: t.name,
        ...(t.title ? { title: t.title } : {}),
        description: t.description ?? "",
        annotations: t.annotations ?? {},
        inputSchema: t.inputSchema ?? {},
      })),
    },
    null,
    2,
  )}\n`;
}

export interface ErrorCode {
  code: string;
  exitCode: 1 | 2;
  where: string;
  message: string;
}

/**
 * Every error code the CLI (--json) and MCP tools can report: `new OpError("code", …)` in the
 * CLI, operations layer and MCP server, plus `new ImportError("code", …)`, which the operations
 * layer passes through with its own code.
 */
export function findErrorCodes(): ErrorCode[] {
  const found = new Map<string, ErrorCode>();
  const files = readdirSync(SRC).filter(
    (f) => f.endsWith(".ts") && !f.endsWith(".test.ts") && f !== "agent-reference.ts",
  );
  for (const file of files.sort()) {
    const text = readFileSync(join(SRC, file), "utf8");
    for (const m of text.matchAll(/new (OpError|ImportError)\(\s*"([a-z_]+)",\s*/g)) {
      const code = m[2] ?? "";
      const rest = text.slice((m.index ?? 0) + m[0].length);
      const literal = /^(`[^`]*`|"[^"]*")/.exec(rest);
      const exit = literal
        ? /^\s*,\s*([12])\s*,?\s*\)/.exec(rest.slice(literal[0].length))?.[1]
        : /^[^;]*?,\s*([12])\s*,?\s*\);/.exec(rest)?.[1];
      const message = literal
        ? (literal[1] ?? "").slice(1, -1).replace(/\$\{[^}]+\}/g, "…")
        : "(depends on the case)";
      const line = text.slice(0, m.index).split("\n").length;
      if (!found.has(code)) {
        found.set(code, {
          code,
          exitCode: exit === "2" ? 2 : 1,
          where: `apps/local/src/${file}:${line}`,
          message,
        });
      }
    }
  }
  return [...found.values()].sort((a, b) => a.code.localeCompare(b.code));
}

export function errorsMarkdown(codes: readonly ErrorCode[]): string {
  const rows = codes.map(
    (c) =>
      `| \`${c.code}\` | ${c.exitCode} | ${c.message.replace(/\|/g, "\\|")} | \`${c.where.replace(/:\d+$/, "")}\` |`,
  );
  return [
    "# Error codes",
    "",
    "Generated by `node apps/local/src/agent-reference.ts`; a test fails if this file is out of date.",
    "",
    'With `--json`, a refused CLI command prints `{"error": {"code": "…", "message": "…"}}` on',
    "stdout and exits with the code below (1 = could not do it, 2 = wrong usage). Unknown commands and",
    "flags print usage and exit 2. MCP tools return the same message with `isError: true`. Branch on",
    "`code`, not on the message text.",
    "",
    "| Code | Exit | Message (… = filled in at run time) | Raised in |",
    "|---|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const out = join(ROOT, "docs/agents");
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "tools.json"), toolsJson(await listTools()));
  writeFileSync(join(out, "errors.md"), errorsMarkdown(findErrorCodes()));
  console.error("Wrote docs/agents/tools.json and docs/agents/errors.md");
}
